export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setValue] = useState<Language>(() => localStorage.getItem('barangai-language') === 'fil' ? 'fil' : 'en')
  useEffect(() => { document.documentElement.lang = language }, [language])
  function setLanguage(value: Language) { localStorage.setItem('barangai-language', value); document.documentElement.lang = value; setValue(value) }
  return <LanguageContext.Provider value={{ language, setLanguage }}>{children}</LanguageContext.Provider>
}

export function useLanguage() { return useContext(LanguageContext) }
export function useText() {
  const { language } = useLanguage()
  return (text: string) => language === 'fil' ? filipino[text] ?? (text.startsWith('Request failed (') ? `Hindi natuloy ang kahilingan ${text.slice(15)}. Subukan muli.` : text) : text
}
export function Txt({ children }: { children: string }) { const t = useText(); return <>{t(children)}</> }
export function LanguageSwitch() {
  const { language, setLanguage } = useLanguage()
  return <button className="language-switch" type="button" aria-label={language === 'en' ? 'Filipino interface' : 'English interface'} onClick={() => setLanguage(language === 'en' ? 'fil' : 'en')}>{language === 'en' ? 'Filipino' : 'English'}</button>
}
